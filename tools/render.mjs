import {existsSync,mkdirSync,readFileSync} from 'node:fs';
import {run} from './common.mjs';
const mode=process.argv[2]||'draft',final=mode==='final';
const fi=process.argv.indexOf('--film'),film=fi<0?'galileo':process.argv[fi+1];
if(!/^[a-z0-9-]+$/.test(film))throw new Error('Invalid film id');
const ri=process.argv.indexOf('--release'),release=ri<0?new Date().toISOString().slice(0,10)+'-v1':process.argv[ri+1];
if(!/^\d{4}-\d{2}-\d{2}-v[1-9]\d*$/.test(release))throw new Error('Use --release YYYY-MM-DD-vN');
const folder=`renders/${film}/${release}`;
mkdirSync(folder,{recursive:true});
const audio='films/'+film+'/assets/mix.wav';
if(!existsSync(audio))throw new Error('Run npm run audio first.');
const reportPath=`films/${film}/assets/audio-report.json`;
const report=existsSync(reportPath)?JSON.parse(readFileSync(reportPath,'utf8')):null;
const basename=final&&report?.delivery?.includes('preview')?'preview-music':mode;
await run(process.execPath,['tools/upstream/render.mjs','films/'+film+'/'+(final?'index.html':'draft.html'),'--root','.', '--workers','2','--fps','30','--audio',audio,'--out',folder+'/'+basename+'.mp4',...(final?['--crf','17']:['--fast'])]);
console.log('Delivery folder: '+folder);
